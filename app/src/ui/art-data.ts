export type Shape = {
  /** path data */
  d?: string;
  /** circle: cx, cy, r */
  c?: [number, number, number];
  /** ellipse: cx, cy, rx, ry */
  e?: [number, number, number, number];
  /** rounded rect: x, y, w, h, radius */
  r?: [number, number, number, number, number];
  /** fill colour (default none) */
  f?: string;
  /** stroke colour */
  s?: string;
  /** stroke width (default 2) */
  w?: number;
  /** rotation: degrees, cx, cy */
  rot?: [number, number, number];
  /** opacity */
  o?: number;
};

